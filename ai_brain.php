   - credit = احنا دفعنا للمورد فعلياً (فلوس طالعة منا) - حدد paid_from_bank بنفس منطق نقطة 1 أعلاه
   - عبارات رمزي الشائعة: "اعطيتوا ذمة من الكاش" / "دفعتلمعي كاش" = credit مع paid_from_bank="cash". "اخذ بضاعة أجل" / "اخذنا بضاعة وعدين" (يعني: وبعدين رح ندفع) = debit مع paid_from_bank=null.
   - ⚠️ حالة نادرة لازم تنتبهلها: لو الجملة قالت إنه **المورد نفسه** هو يلي دفع لنا (مثلاً "رمزي دفع 20 دينار" حيث رمزي هو المورد، أو "المورد رجعلنا فلوس" أو "استرجعنا من المورد") - هاي فلوس **داخلة لنا** مش طالعة منا، وهاي حالة غامضة ونادرة (الموردين عادة بيستلموا مش يدفعوا). لا تفترض إنها "دفعنا له" تلقائياً بس لأنها الحالة الأكتر شيوعاً - استخدم action="unclear" واسأل: "قصدك انت دفعت للمورد [الاسم]، ولا هو رجّعلك فلوس (مرتجع/استرداد)؟" خصوصاً إذا الاسم نفسه (الفاعل) هو المورد مش "احنا/نحن".
   - ⚠️ حالة "رجّعنا بضاعة للمورد" / "مرتجع للمورد" (إحنا يلي رجّعنا البضاعة له، مش هو دفعلنا فلوس): هاي بتقلل دينك عليه (زي دفعة بالضبط، نفس اتجاه credit) بس **بدون أي حركة نقدية إطلاقاً** - لا تعتبرها "استلمنا بضاعة" (debit، هاد عكس المطلوب تماماً). سجلها type="credit"، و**لا تحط paid_from_bank** (سيبها فاضية) بل احط description توضح "مرتجع بضاعة" حتى تنعرف كسبب مقبول بدون بنك.

